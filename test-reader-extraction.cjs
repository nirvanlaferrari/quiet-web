const assert=require("node:assert/strict");
const fs=require("node:fs");
const {JSDOM}=require("jsdom");
const {Readability}=require("@mozilla/readability");
const createPurifier=require("dompurify");
const {window}=new JSDOM("",{url:"https://reader.example",runScripts:"outside-only"});
window.Readability=Readability;window.DOMPurify=createPurifier(window);
window.eval(fs.readFileSync(require("path").join(__dirname,"../reader-extraction.js"),"utf8"));
const unsafe='<p onclick="alert(1)">Read me</p><script>alert(1)</script><img src="x" onerror="alert(1)"><a href="javascript:alert(1)">click</a><iframe src="https://evil.example"></iframe><svg onload="alert(1)"></svg>';
const clean=window.ReaderContent.sanitize(unsafe);
const output=new window.DOMParser().parseFromString(clean,"text/html");
assert.equal(output.querySelector("script,iframe,svg"),null);
assert.equal(output.querySelector("[onclick],[onerror],[onload]"),null);
assert.equal(output.querySelector("a").getAttribute("href"),null);
const prose="A reader should be able to follow this complete article without the surrounding navigation. ".repeat(25);
const article=window.ReaderContent.extract(`<html><head><title>Real article</title></head><body><nav>menu menu menu</nav><article><h1>Real article</h1><p>${prose}</p><h2>A useful heading</h2><p>${prose}<a href="/source">Source</a></p>${unsafe}</article></body></html>`,"https://publisher.example/post");
assert(article&&article.paragraphs.length>=2);assert(article.html.includes("A useful heading"));
assert(article.html.includes("https://publisher.example/source"));
assert(!/onclick=|onerror=|<script|<iframe|javascript:/i.test(article.html));
assert.equal(window.ReaderContent.extract("<html><body></body></html>","https://publisher.example/"),null);
console.log("PASS: Readability content extraction, headings/relative links, empty-page fallback, script/event/unsafe-URL sanitization");
window.close();
